#!/usr/bin/env node
'use strict';
/* ==========================================================================
 * CppPractice — brand synchroniser
 * --------------------------------------------------------------------------
 * js/brand.js and js/ads.js are the single source of truth for the site's name,
 * links and AdSense configuration. The running app reads them directly; this
 * script pushes the same values into the files that cannot:
 *
 *   index.html    the <title>/meta block between the brand:head markers,
 *                 plus a canonical link, Open Graph/Twitter tags and (once a
 *                 publisher id is set) the AdSense account verification meta
 *   ads.txt       the AdSense authorisation line for the domain root
 *   package.json  name + description   (and the name in package-lock.json)
 *   README.md     the top heading and the repository / live-site links
 *
 *   node scripts/sync-brand.js            write the files
 *   node scripts/sync-brand.js --check    change nothing; exit 1 if out of date
 * ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CHECK = process.argv.includes('--check');

const brand = require(path.join(ROOT, 'js/brand.js'));
const ads = require(path.join(ROOT, 'js/ads.js'));

const PUBLISHER_RE = /^ca-pub-\d{16}$/;
const staged = [];

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
function jsonEsc(s) { return String(s == null ? '' : s).replace(/\\/g, '\\\\').replace(/"/g, '\\"'); }
function canonical() { return String(brand.liveUrl || '').replace(/\/?$/, '/'); }

function stage(file, next) {
  const abs = path.join(ROOT, file);
  const before = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
  staged.push({ file, abs, before, next, changed: before !== next });
}

function fatal(msg) {
  console.error('✗ ' + msg);
  process.exit(1);
}

/* ----------------------------- index.html ------------------------------- */
// Keep the generated block in whatever newline style the file already uses, so
// the check never reports false drift on a CRLF checkout.
let HEAD_NL = '\n';

function headBlock() {
  const title = esc(brand.title || brand.name);
  const desc = esc(brand.description || brand.shortDescription || '');
  const url = esc(canonical());
  const lines = [
    '  <!-- brand:head — generated by `npm run brand:sync` from js/brand.js. Do not edit by hand. -->',
    '  <title>' + title + '</title>',
    '  <meta name="description" content="' + desc + '">',
    '  <link rel="canonical" href="' + url + '">',
    '  <meta name="theme-color" content="' + esc(brand.themeColor || '#6366f1') + '">',
    '  <meta property="og:type" content="website">',
    '  <meta property="og:site_name" content="' + esc(brand.name) + '">',
    '  <meta property="og:title" content="' + title + '">',
    '  <meta property="og:description" content="' + desc + '">',
    '  <meta property="og:url" content="' + url + '">',
    '  <meta name="twitter:card" content="summary">',
    '  <meta name="twitter:title" content="' + title + '">',
    '  <meta name="twitter:description" content="' + esc(brand.shortDescription || brand.description || '') + '">',
  ];
  // Only present once AdSense is configured — this is one of the ways Google
  // verifies that you own the site.
  if (PUBLISHER_RE.test(String(ads.publisherId || '').trim())) {
    lines.push('  <meta name="google-adsense-account" content="' + esc(String(ads.publisherId).trim()) + '">');
  }
  lines.push('  <!-- /brand:head -->');
  return lines.join(HEAD_NL);
}

{
  const src = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  HEAD_NL = src.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  // The match deliberately includes the block's leading indentation so that
  // replacing it is idempotent (otherwise each run would indent it further).
  const HEAD_RE = /[ \t]*<!--\s*brand:head[\s\S]*?<!--\s*\/brand:head\s*-->/;
  if (!HEAD_RE.test(src)) {
    fatal('index.html is missing its <!-- brand:head --> … <!-- /brand:head --> block');
  }
  stage('index.html', src.replace(HEAD_RE, headBlock()));
}

/* -------------------------------- ads.txt ------------------------------- */
{
  const pub = String(ads.publisherId || '').trim();
  const existing = fs.existsSync(path.join(ROOT, 'ads.txt')) ? fs.readFileSync(path.join(ROOT, 'ads.txt'), 'utf8') : '';
  const NL = existing.indexOf('\r\n') !== -1 ? '\r\n' : '\n';
  const body = PUBLISHER_RE.test(pub)
    ? 'google.com, ' + pub + ', DIRECT, f08c47fec0942fa0' + NL
    : '# Advertising is not configured yet.' + NL +
      '# 1. Set publisherId in js/ads.js' + NL +
      '# 2. Run `npm run brand:sync`' + NL +
      '# NOTE: ads.txt is only honoured at the ROOT of your own domain' + NL +
      '#       (https://your-domain/ads.txt) — see README → AdSense checklist.' + NL;
  stage('ads.txt', body);
}

/* ------------------------------ package.json ----------------------------- */
const slug = String(brand.name).toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '') || 'cpp-practice-website';
{
  const src = fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8');
  let next = src.replace(/("name"\s*:\s*")[^"]*(")/, '$1' + slug + '$2');
  next = next.replace(/("description"\s*:\s*")[^"]*(")/, '$1' + jsonEsc(brand.description) + '$2');
  stage('package.json', next);
}
{
  const lockPath = path.join(ROOT, 'package-lock.json');
  if (fs.existsSync(lockPath)) {
    const src = fs.readFileSync(lockPath, 'utf8');
    // Only rewrite the top-level package name, never dependency names.
    const oldName = (src.match(/"name"\s*:\s*"([^"]*)"/) || [])[1];
    if (oldName && oldName !== slug) {
      stage('package-lock.json', src.split('"name": "' + oldName + '"').join('"name": "' + slug + '"'));
    }
  }
}

/* -------------------------------- README.md ------------------------------ */
{
  const readmePath = path.join(ROOT, 'README.md');
  if (fs.existsSync(readmePath)) {
    let next = fs.readFileSync(readmePath, 'utf8');
    next = next.replace(/^#\s+.*$/m, '# ' + brand.name);
    if (brand.repository) {
      next = next.replace(/https:\/\/github\.com\/[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+/g, brand.repository);
    }
    if (brand.liveUrl) {
      next = next.replace(/https:\/\/[A-Za-z0-9_.-]+\.github\.io\/[A-Za-z0-9_.-]+\/?/g, canonical());
    }
    stage('README.md', next);
  }
}

/* --------------------------------- apply --------------------------------- */
const stale = staged.filter((s) => s.changed);

if (CHECK) {
  if (stale.length) {
    console.error('✗ files are out of date with js/brand.js / js/ads.js:');
    stale.forEach((s) => {
      console.error('    ' + s.file);
      const a = String(s.before == null ? '' : s.before).split('\n');
      const b = String(s.next).split('\n');
      for (let i = 0; i < Math.max(a.length, b.length); i++) {
        if (a[i] !== b[i]) {
          console.error('      line ' + (i + 1));
          console.error('        file: ' + JSON.stringify(a[i]));
          console.error('        want: ' + JSON.stringify(b[i]));
          break;
        }
      }
    });
    console.error('  run: npm run brand:sync');
    process.exit(1);
  }
  console.log('✓ brand files are in sync with js/brand.js and js/ads.js');
  process.exit(0);
}

stale.forEach((s) => {
  fs.writeFileSync(s.abs, s.next);
  console.log((s.before === null ? '＋ created ' : '✎ updated ') + s.file);
});
if (!stale.length) console.log('nothing to do — already in sync');
if (PUBLISHER_RE.test(String(ads.publisherId || '').trim())) {
  console.log('\n  ads.txt  →  google.com, ' + String(ads.publisherId).trim() + ', DIRECT, f08c47fec0942fa0');
} else {
  console.log('\n  Advertising is OFF (no publisherId in js/ads.js) — ads.txt is a placeholder.');
}
